// Map a prompts.json key to its intake folder: "default" -> photos/, any
// other key -> photos-<kebab-case(key)>/ ("keepText" -> photos-keep-text/).
const kebab = (s) => s
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/[\s_]+/g, '-')
  .toLowerCase();
const intakeDir = (promptKey) => promptKey === 'default' ? 'photos' : `photos-${kebab(promptKey)}`;

function loadPrompts() {
  if (!existsSync(PROMPTS_FILE)) return null;
  try {
    return JSON.parse(readFileSync(PROMPTS_FILE, 'utf8'));
  } catch (err) {
    throw new Error(`could not parse ${PROMPTS_FILE}: ${err.message}`);
  }
}

function writeStarterPrompts() {
  if (existsSync(PROMPTS_FILE)) {
    console.log(`${PROMPTS_FILE} already exists — leaving it alone.`);
    return;
  }
  writeFileSync(PROMPTS_FILE, `${JSON.stringify(STARTER_PROMPTS, null, 2)}\n`);
  console.log(`wrote ${PROMPTS_FILE} — edit the prompts, then run "gemini-vectorize".`);
}

const RASTER = /\.(tiff?|png|jpe?g|webp)$/i;
const listRasters = (dir) => existsSync(dir)
  ? readdirSync(dir).filter((f) => RASTER.test(f)).sort()
  : [];

// Convert/shrink to a PNG/JPEG both APIs accept (<=5MB, <=4096px).
// Oversized files go to JPEG q92 (a PNG can stay over the byte limit).
// Uses macOS's `sips`; if it's missing (non-macOS), the file is sent as-is.
function prepare(file, { forceJpeg = false } = {}) {
  const needsConvert = /\.(tiff?|webp)$/i.test(file);
  const tooBig = statSync(file).size > 5 * 1024 * 1024;
  let maxDim = 0;
  try {
    const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' });
    maxDim = Math.max(...[...out.matchAll(/pixel\w+: (\d+)/g)].map((m) => Number(m[1])));
  } catch { /* sips missing (non-macOS): send file as-is */ }
  if (!needsConvert && !tooBig && maxDim <= 4096 && !forceJpeg) return { path: file, cleanup: false };

  const jpeg = tooBig || forceJpeg;
  const tmp = path.join(tmpdir(), path.basename(file).replace(/\.\w+$/, jpeg ? '.jpg' : '.png'));
  const args = jpeg
    ? ['-s', 'format', 'jpeg', '-s', 'formatOptions', '92']
    : ['-s', 'format', 'png'];
  if (maxDim > 4096) args.push('-Z', '4096');
  execFileSync('sips', [...args, file, '--out', tmp], { stdio: 'ignore' });
  return { path: tmp, cleanup: true };
}

const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };

async function geminiRedraw(file, prompt, key) {
  const mime = MIME[path.extname(file).toLowerCase()] ?? 'image/png';
  const body = {
    contents: [{
      parts: [
        { inline_data: { mime_type: mime, data: readFileSync(file).toString('base64') } },
        { text: prompt },
      ],
    }],
    generationConfig: { responseModalities: ['TEXT', 'IMAGE'] },
  };
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`${GEMINI_API}/models/${MODEL}:generateContent`, {
      method: 'POST',
      headers: { 'x-goog-api-key': key, 'content-type': 'application/json' },
      body: JSON.stringify(body),
    });
    if (res.status === 429 || res.status >= 500) {
      if (attempt >= 3) throw new Error(`gemini failed after ${attempt} tries (${res.status})`);
      await new Promise((r) => setTimeout(r, attempt * 10_000));
      continue;
    }
    if (!res.ok) throw new Error(`gemini ${res.status}: ${(await res.text()).slice(0, 300)}`);
    const data = await res.json();
    const part = data.candidates?.[0]?.content?.parts?.find((p) => p.inlineData || p.inline_data);
    const img = part?.inlineData ?? part?.inline_data;
    if (!img) {
      const text = data.candidates?.[0]?.content?.parts?.map((p) => p.text).join(' ');
      throw new Error(`no image in response${text ? `: ${text.slice(0, 200)}` : ''}`);
    }
    return Buffer.from(img.data, 'base64');
  }
}

async function recraftCall(url, file, key) {
  const body = new FormData();
  body.append('file', new Blob([readFileSync(file)]), path.basename(file));
  body.append('response_format', 'b64_json');
  const res = await fetch(url, {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}` },
    body,
  });
  if (!res.ok) throw new Error(`recraft ${path.basename(url)} failed (${res.status}): ${await res.text()}`);
  const data = await res.json();
  const img = data.image ?? data.data?.[0];
  if (img?.b64_json) return Buffer.from(img.b64_json, 'base64');
  if (img?.url) {
    const dl = await fetch(img.url);
    if (!dl.ok) throw new Error(`result download failed (${dl.status})`);
    return Buffer.from(await dl.arrayBuffer());
  }
  throw new Error(`unexpected response shape: ${JSON.stringify(data).slice(0, 300)}`);
}

// Run the finished SVG through svg-color-rinse for print-ready color
// normalization. Best-effort: if it's not available, note that and move on —
// the SVG output has already been written either way.
function runRinse(svgPath) {
  const custom = process.env.SVG_COLOR_RINSE;
  try {
    if (custom) {
      execFileSync(custom, ['--optimize', '--in-place', svgPath], { stdio: 'inherit' });
    } else {
      execFileSync('npx', ['--yes', 'svg-color-rinse', '--optimize', '--in-place', svgPath], { stdio: 'inherit' });
    }
  } catch {
    console.log('note: install svg-color-rinse for print-ready color normalization (npm install -g svg-color-rinse)');
  }
}

async function redrawStage() {
  const key = process.env.GEMINI_API_KEY;
  if (!key) { console.error('set GEMINI_API_KEY (aistudio.google.com/apikey)'); process.exit(1); }

  let prompts;
  try {
    prompts = loadPrompts() ?? {};
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
  if (promptOverride) prompts.default = promptOverride;
  if (!Object.keys(prompts).length) {
    console.error('no prompts found — run "gemini-vectorize init" to create prompts.json, '
      + 'or pass --prompt "..."');
    process.exit(1);
  }
  for (const [k, v] of Object.entries(prompts)) {
    const ok = typeof v === 'string'
      ? v.length > 0
      : Array.isArray(v) && v.length > 0 && v.every((p) => typeof p === 'string' && p.length > 0);
    if (!ok) {
      console.error(`prompts.json: "${k}" must be a non-empty string or a non-empty array of strings`);
      process.exit(1);
    }
  }

  mkdirSync('redrawn', { recursive: true });
  console.log(`redraw stage — model: ${MODEL}`);

  // Each prompts.json key maps to an intake folder: "default" -> photos/,
  // any other key K -> photos-<kebab-case(K)>/ ("keepText" -> photos-keep-text/).
  // Missing/empty folders are simply skipped. A value may be an array of
  // prompt variants; one is chosen at random per image (deleting an output
  // and re-running re-rolls the variant).
  const redrawDest = (src) => path.join('redrawn', path.basename(src).replace(/\.\w+$/, '.png'));

  const jobs = [];
  for (const [promptKey, promptValue] of Object.entries(prompts)) {
    const dir = intakeDir(promptKey);
    jobs.push(...listRasters(dir).map((f) => [path.join(dir, f), promptValue]));
  }
  if (!jobs.length) {
    const dirs = Object.keys(prompts).map((k) => `${intakeDir(k)}/`).join(', ');
    console.log(`no photos found — drop images into ${dirs}`);
  }

  // Cost estimate: idempotency-filtered pending images only. Includes the
  // Recraft cost the (separate) vectorize stage will later incur on these
  // same redraws, so the number reflects the full pipeline cost, not just
  // this stage.
  const pending = jobs.filter(([src]) => !existsSync(redrawDest(src)));
  const geminiPrice = pro ? GEMINI_PRICE_PRO : GEMINI_PRICE_FLASH;
  const geminiCost = pending.length * geminiPrice;
  const recraftCost = pending.length * (RECRAFT_PRICE_UPSCALE + RECRAFT_PRICE_VECTORIZE);
  const totalCost = geminiCost + recraftCost;
  const plural = pending.length === 1 ? '' : 's';
  console.log(`cost estimate: ${pending.length} pending image${plural} -> `
    + `~$${geminiCost.toFixed(2)} Gemini (${MODEL}) + ~$${recraftCost.toFixed(2)} Recraft `
    + `(later vectorize stage) = ~$${totalCost.toFixed(2)} total`);
  if (maxImages != null && pending.length > maxImages) {
    console.log(`--max-images ${maxImages}: only ${maxImages} of ${pending.length} pending `
      + `image${plural} will run this invocation — re-run to continue with the rest.`);
  }

  if (pending.length > 0) await confirmProceed();

  let done = 0, skipped = 0, failed = 0, deferred = 0, attempted = 0;
  for (const [src, promptValue] of jobs) {
    const dest = redrawDest(src);
    if (existsSync(dest)) { skipped++; continue; }
    if (maxImages != null && attempted >= maxImages) { deferred++; continue; }
    attempted++;
    let jobPrompt = promptValue;
    let variantNote = '';
    if (Array.isArray(promptValue)) {
      const i = Math.floor(Math.random() * promptValue.length);
      jobPrompt = promptValue[i];
      variantNote = ` [variant ${i + 1}/${promptValue.length}]`;
    }
    process.stdout.write(`${path.basename(src)}${variantNote} ... `);
    let prepared;
    try {
      prepared = prepare(src);
      writeFileSync(dest, await geminiRedraw(prepared.path, jobPrompt, key));
      console.log('redrawn');
      done++;
    } catch (err) {
      console.log(`FAILED: ${err.message}`);
      failed++;
    } finally {
      if (prepared?.cleanup) rmSync(prepared.path, { force: true });
    }
  }
  const deferredNote = deferred
    ? `, ${deferred} deferred (--max-images ${maxImages} — re-run to continue)`
    : '';
  console.log(`redraw: ${done} done, ${skipped} already done, ${failed} failed${deferredNote}\n`);
}

async function vectorizeStage() {
  const key = process.env.RECRAFT_API_KEY;
  if (!key) { console.error('set RECRAFT_API_KEY (recraft.ai/profile/api)'); process.exit(1); }
  const upscale = !noUpscale;
  mkdirSync('vectorized', { recursive: true });
  if (upscale) mkdirSync('upscaled', { recursive: true });
  console.log(`vectorize stage${upscale ? ' (with crisp upscale)' : ''}`);

  const startBalance = await recraftBalance(key);
  if (startBalance != null) console.log(`Recraft balance: ${startBalance} credits`);

  const jobs = listRasters('redrawn').map((f) => path.join('redrawn', f));
  let done = 0, skipped = 0, failed = 0, units = 0;
  for (const src of jobs) {
    const base = path.basename(src).replace(/\.\w+$/, '');
    const dest = path.join('vectorized', `${base}.svg`);
    if (existsSync(dest)) { skipped++; continue; }
    process.stdout.write(`${path.basename(src)} ... `);
    let prepared;
    try {
      let vecInput = src;
      if (upscale) {
        const up = path.join('upscaled', `${base}.jpg`);
        if (!existsSync(up)) {
          prepared = prepare(src);
          const raw = path.join(tmpdir(), `${base}-up.webp`);
          writeFileSync(raw, await recraftCall(RECRAFT_UPSCALE, prepared.path, key));
          units += 4;
          process.stdout.write('upscaled ... ');
          // upscale output can exceed the vectorize input limits; JPEG q92 + 4096px cap
          const shrunk = prepare(raw, { forceJpeg: true });
          writeFileSync(up, readFileSync(shrunk.path));
          rmSync(raw, { force: true });
          if (shrunk.cleanup) rmSync(shrunk.path, { force: true });
          if (prepared.cleanup) rmSync(prepared.path, { force: true });
          prepared = null;
        }
        vecInput = up;
      }
      prepared = prepare(vecInput);
      writeFileSync(dest, await recraftCall(RECRAFT_VECTORIZE, prepared.path, key));
      units += 10;
      console.log('vectorized');
      runRinse(dest);
      done++;
    } catch (err) {
      console.log(`FAILED: ${err.message}`);
      failed++;
    } finally {
      if (prepared?.cleanup) rmSync(prepared.path, { force: true });
    }
  }
  console.log(`vectorize: ${done} done (${units} units), ${skipped} already done, ${failed} failed`);

  const endBalance = await recraftBalance(key);
  if (endBalance != null) console.log(`Recraft balance: ${endBalance} credits`);
}

async function balanceCommand() {
  const key = process.env.RECRAFT_API_KEY;
  if (!key) { console.error('set RECRAFT_API_KEY (recraft.ai/profile/api)'); process.exit(1); }
  const balance = await recraftBalance(key);
  if (balance == null) {
    console.error('could not fetch Recraft balance (bad key, or the API is unreachable)');
    process.exit(1);
  }
  console.log(`Recraft balance: ${balance} credits`);
}

async function listModels() {
  const key = process.env.GEMINI_API_KEY;
  if (!key) { console.error('set GEMINI_API_KEY'); process.exit(1); }
  const res = await fetch(`${GEMINI_API}/models?pageSize=1000`, { headers: { 'x-goog-api-key': key } });
  if (!res.ok) throw new Error(`list models failed (${res.status}): ${await res.text()}`);
  const { models = [] } = await res.json();
  for (const m of models) {
    if (/image/i.test(m.name) || /image/i.test(m.description ?? '')) {
      console.log(`${m.name.replace('models/', '')}  —  ${m.displayName}`);
    }
  }
}

if (subcommand === 'redraw') await redrawStage();
else if (subcommand === 'vectorize') await vectorizeStage();
else if (subcommand === 'models') await listModels();
else if (subcommand === 'init') writeStarterPrompts();
else if (subcommand === 'balance') await balanceCommand();
else { await redrawStage(); await vectorizeStage(); }
