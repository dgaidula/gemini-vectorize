#!/usr/bin/env node
// gemini-vectorize.mjs — photos -> Gemini "nano banana" redraw -> Recraft
// crisp-upscale -> Recraft vectorize -> svg-color-rinse
//
// Stages:
//   redraw     photos/ + photos-<variant>/ -> redrawn/
//              (Gemini image models; each prompts.json key maps to an intake
//               folder — "default" -> photos/, any other key K ->
//               photos-<kebab-case(K)>/, e.g. "keepText" -> photos-keep-text/)
//   vectorize  redrawn/ -> upscaled/ -> vectorized/
//              (Recraft crisp upscale 4 units + vectorize 10 units per image,
//               then svg-color-rinse --optimize on each SVG)
//
// Usage:
//   gemini-vectorize                 # both stages (same as "run")
//   gemini-vectorize run             # both stages
//   gemini-vectorize redraw          # only generate redraws
//   gemini-vectorize vectorize       # only upscale + vectorize + rinse
//   gemini-vectorize models          # list Gemini image models for your key
//   gemini-vectorize init            # write a starter prompts.json
//   gemini-vectorize balance         # print the Recraft credit balance
//   --pro                            # use the "pro" Gemini image model for redraw
//   --no-upscale                     # skip the crisp-upscale step
//   --prompt "..."                   # override the default (no-text) prompt
//   --yes                            # skip the pre-redraw cost confirmation prompt
//   --max-images N                   # cap NEW redraws generated by this run
//
// Env: GEMINI_API_KEY (redraw), RECRAFT_API_KEY (vectorize),
//      GEMINI_MODEL / GEMINI_MODEL_PRO to override model ids,
//      SVG_COLOR_RINSE to point at a local svg-color-rinse CLI/executable.
//
// Idempotent: any output that already exists is skipped. To retry a bad
// redraw, delete it from redrawn/ (and its SVG from vectorized/) and re-run.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createInterface } from 'node:readline/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import process from 'node:process';

const RECRAFT_VECTORIZE = 'https://external.api.recraft.ai/v1/images/vectorize';
const RECRAFT_UPSCALE = 'https://external.api.recraft.ai/v1/images/crispUpscale';
const RECRAFT_ME = 'https://external.api.recraft.ai/v1/users/me';
const GEMINI_API = 'https://generativelanguage.googleapis.com/v1beta';

// Approximate per-image prices, 2026 — these are rough guides for the
// pre-flight cost estimate, not billing quotes; update if provider pricing
// changes.
const GEMINI_PRICE_FLASH = 0.067; // flash-tier Gemini image redraw
const GEMINI_PRICE_PRO = 0.134; // pro-tier Gemini image redraw
const RECRAFT_PRICE_UPSCALE = 0.004; // Recraft crisp-upscale, 4 units
const RECRAFT_PRICE_VECTORIZE = 0.01; // Recraft vectorize, 10 units

