function parseArgs(argv) {
  const flags = argv.slice(2);
  const subcommands = new Set(['run', 'redraw', 'vectorize', 'models', 'init', 'balance']);
  let subcommand = 'run';
  let pro = false;
  let noUpscale = false;
  let prompt = null;
  let help = false;
  let yes = false;
  let maxImages = null;

  for (let i = 0; i < flags.length; i++) {
    const a = flags[i];
    if (a === '--pro') pro = true;
    else if (a === '--no-upscale') noUpscale = true;
    else if (a === '--prompt') prompt = flags[++i];
    else if (a === '--yes') yes = true;
    else if (a === '--max-images') maxImages = Number(flags[++i]);
    else if (a === '-h' || a === '--help') help = true;
    else if (!a.startsWith('--') && subcommands.has(a)) subcommand = a;
  }
  return { subcommand, pro, noUpscale, prompt, help, yes, maxImages };
}

const { subcommand, pro, noUpscale, prompt: promptOverride, help, yes, maxImages } = parseArgs(process.argv);

// Bare invocation (no subcommand, no flags) prints usage instead of assuming
// "run" — that would otherwise fail immediately on a missing API key.
if (help || process.argv.length === 2) {
  console.log(HELP);
  process.exit(0);
}

if (maxImages != null && (!Number.isInteger(maxImages) || maxImages < 0)) {
  console.error('--max-images requires a non-negative integer');
  process.exit(1);
}

// Ask "Proceed? [y/N]" before spending money, unless --yes was passed. A
// non-interactive stdin (CI, an unattended agent run) can't answer a
// prompt, so it aborts instead of hanging — pass --yes to run unattended.
async function confirmProceed() {
  if (yes) return;
  if (!process.stdin.isTTY) {
    console.error('stdin is not interactive — pass --yes to proceed without a confirmation prompt.');
    process.exit(1);
  }
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  let answer;
  try {
    answer = await rl.question('Proceed? [y/N] ');
  } finally {
    rl.close();
  }
  if (!/^y(es)?$/i.test(answer.trim())) {
    console.log('aborted.');
    process.exit(0);
  }
}

// Best-effort: fetch the Recraft account's remaining credit balance. Returns
// null (never throws) so callers can skip silently on failure.
async function recraftBalance(key) {
  try {
    const res = await fetch(RECRAFT_ME, { headers: { Authorization: `Bearer ${key}` } });
    if (!res.ok) return null;
    const data = await res.json();
    return data.credits ?? data.balance ?? data.credit_balance ?? data.creditBalance ?? null;
  } catch {
    return null;
  }
}

